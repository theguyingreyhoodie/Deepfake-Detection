"""Run pipeline steps as private Kaggle jobs ("kernels") from this machine.

Each job is a self-contained Python script: the ``deepfake_detector`` package is zipped and embedded
in it (base64), so a job always runs exactly the code that was on disk when it was pushed.
Inputs are Kaggle datasets (raw videos) or the outputs of earlier jobs (face-crop shards, checkpoints),
which Kaggle mounts read-only under /kaggle/input; outputs are whatever the job writes to
/kaggle/working. Jobs run under the Kaggle account named by the KAGGLE_USER environment variable
(the Kaggle CLI must be signed in to that account).

    python kaggle/launch.py push extract-ffpp      # start a job
    python kaggle/launch.py status                 # status of every job
    python kaggle/launch.py fetch extract-ffpp     # download its log and small outputs
    python kaggle/launch.py queue a b c            # start CPU jobs as concurrent-session slots free up
    python kaggle/launch.py after x a b            # start job x once jobs a and b are complete
"""

from __future__ import annotations

import base64
import io
import json
import os
import re
import subprocess
import sys
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "kaggle"
KAGGLE = str(ROOT / ".venv" / "bin" / "kaggle")
USER = os.environ.get("KAGGLE_USER") or sys.exit("Set KAGGLE_USER to your Kaggle username.")
PREFIX = "dfd-"

sys.path.insert(0, str(Path(__file__).parent))
from jobs import JOBS  # noqa: E402

RUNNER = '''# Auto-generated by kaggle/launch.py -- job: {name}
import base64, io, os, subprocess, sys, zipfile, time
SRC = "/tmp/dfd_src"
zipfile.ZipFile(io.BytesIO(base64.b64decode(PACKAGE))).extractall(SRC)
t = time.time()
subprocess.run("pip install -q {pip} 2>&1 | grep -v -i warning | tail -3", shell=True)
print(f"pip install took {{time.time() - t:.0f}}s", flush=True)
env = dict(os.environ, PYTHONPATH=SRC, PYTHONUNBUFFERED="1", DEEPFAKE_CACHE="/tmp/dfd_cache")
for cmd in {commands!r}:
    print("$", cmd, flush=True)
    code = subprocess.run(cmd, shell=True, env=env).returncode
    if code != 0:
        print(f"command failed with exit code {{code}}", flush=True)
        sys.exit(code)
'''


def package_b64() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted((ROOT / "deepfake_detector").rglob("*")):
            if path.suffix in (".py", ".json") and "__pycache__" not in path.parts:
                z.write(path, path.relative_to(ROOT))
    return base64.b64encode(buf.getvalue()).decode()


def build(name: str) -> Path:
    job = JOBS[name]
    out = BUILD / name
    out.mkdir(parents=True, exist_ok=True)
    script = f"PACKAGE = {package_b64()!r}\n" + RUNNER.format(
        name=name, pip=job.get("pip", "onnxruntime opencv-python-headless"), commands=job["commands"])
    (out / "run.py").write_text(script)
    gpu = job.get("gpu", False)
    meta = {
        "id": f"{USER}/{PREFIX}{name}",
        "title": f"{PREFIX}{name}",
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_tpu": False,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4" if gpu else "",
        "dataset_sources": job.get("datasets", []),
        "kernel_sources": [f"{USER}/{PREFIX}{k}" for k in job.get("inputs", [])],
        "competition_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    return out


def push(name: str) -> None:
    out = build(name)
    print(subprocess.run([KAGGLE, "kernels", "push", "-p", str(out)], capture_output=True, text=True).stdout.strip())


def status(names: list[str]) -> None:
    for name in names or JOBS:
        r = subprocess.run([KAGGLE, "kernels", "status", f"{USER}/{PREFIX}{name}"], capture_output=True, text=True)
        text = (r.stdout + r.stderr).strip().splitlines()
        print(f"{name:24s} {text[-1].split('status')[-1].strip() if text else '?'}")


def job_status(name: str) -> str:
    r = subprocess.run([KAGGLE, "kernels", "status", f"{USER}/{PREFIX}{name}"], capture_output=True, text=True)
    m = re.search(r"KernelWorkerStatus\.([A-Z_]+)", r.stdout + r.stderr)
    return m.group(1) if m else "NOT_FOUND"


def queue(names: list[str], cpu_slots: int = 5, poll: int = 300) -> None:
    """Push CPU jobs as Kaggle's limit of 5 concurrent batch CPU sessions allows.

    Only the jobs started here are polled (every ``poll`` seconds), keeping API traffic low;
    Kaggle rate-limits accounts that poll too often.
    """
    pending, started, finished = list(names), [], set()
    while pending:
        running = 0
        for name in started:
            if name in finished:
                continue
            st = job_status(name)
            if st in ("RUNNING", "QUEUED", "NOT_FOUND"):  # NOT_FOUND right after a push, or rate limited
                running += 1
            else:
                finished.add(name)
            time.sleep(2)
        free = cpu_slots - running
        while free > 0 and pending:
            name = pending[0]
            r = subprocess.run([KAGGLE, "kernels", "push", "-p", str(build(name))], capture_output=True, text=True)
            text = (r.stdout + r.stderr).strip()
            if "successfully pushed" in text:
                print(time.strftime("%H:%M"), "started", name, flush=True)
                started.append(pending.pop(0))
                free -= 1
            else:
                print(time.strftime("%H:%M"), "could not start", name, "-", text[-120:], flush=True)
                break
        if pending:
            time.sleep(poll)
    print("all queued jobs started", flush=True)


def after(name: str, prerequisites: list[str], poll: int = 600) -> None:
    """Push ``name`` once every prerequisite job is COMPLETE; give up if one fails."""
    waiting = set(prerequisites)
    while waiting:
        for job in sorted(waiting):
            st = job_status(job)
            if st == "COMPLETE":
                waiting.discard(job)
                print(time.strftime("%H:%M"), job, "complete", flush=True)
            elif st in ("ERROR", "CANCEL_ACKNOWLEDGED", "CANCEL_REQUESTED"):
                print(time.strftime("%H:%M"), job, st, "- not starting", name, flush=True)
                return
            time.sleep(2)
        if waiting:
            time.sleep(poll)
    push(name)


def fetch(name: str, pattern: str = "") -> Path:
    out = ROOT / "build" / "outputs" / name
    out.mkdir(parents=True, exist_ok=True)
    cmd = [KAGGLE, "kernels", "output", f"{USER}/{PREFIX}{name}", "-p", str(out), "-o"]
    if pattern:
        cmd += ["--file-pattern", pattern]
    print(subprocess.run(cmd, capture_output=True, text=True).stdout.strip()[-500:])
    for log in out.glob("*.log"):  # Kaggle logs are JSON lists of {stream_name, time, data}
        try:
            text = "".join(e.get("data", "") for e in json.loads(log.read_text()))
            log.with_suffix(".txt").write_text(text)
        except json.JSONDecodeError:
            pass
    return out


if __name__ == "__main__":
    action, *rest = sys.argv[1:] or ["status"]
    if action == "push":
        for n in rest:
            push(n)
    elif action == "build":
        for n in rest:
            print(build(n))
    elif action == "status":
        status(rest)
    elif action == "queue":
        queue(rest)
    elif action == "after":  # after JOB PREREQ1 PREREQ2 ...
        after(rest[0], rest[1:])
    elif action == "fetch":
        fetch(rest[0], rest[1] if len(rest) > 1 else "")
    else:
        raise SystemExit(__doc__)
